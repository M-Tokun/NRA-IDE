class Node(ABC):
    def __init__(self, name: str):
        self.name = name
        self._logger = logging.getLogger(f"NRA.{name}")

    @abstractmethod
    def process(self, token: Token) -> Token: ...

    def _record(self, token: Token) -> Token:
        token.snapshot(self.name)
        return token


class SafetyNode(Node):
    """Inference Diode cum Safety Verification Node. Applies all Laws."""

    def __init__(self, name: str, laws: List[Law]):
        super().__init__(name)
        self.laws = laws

    def process(self, token: Token) -> Token:
        for law in self.laws:
            T = law.tension(token)
            if T > 0:
                token.state.tension = T
            if not law.check(token):
                self._logger.warning(f"Violation: {law.name} | T={T:.4f} | v={token.state.value:.3f}")
                token.log_violation(law.name)
                result = law.correct(token)
                if result is None:
                    token.meta["infeasible"] = True
                    self._logger.error(f"Infeasibility: {law.name}")
                    return self._record(token)
                token = result
        return self._record(token)


class DynamicsNode(Node):
    """
    State Transition Node.
    Can inject `transition_fn`: (DynamicState, cycle) -> DynamicState externally.
    Swapped out for each medium.
    """

    def __init__(
        self,
        name: str,
        transition_fn: Optional[Callable] = None,
        raw_max: float = 100.0,
    ):
        super().__init__(name)
        self.transition_fn = transition_fn or self._default_transition
        self.raw_max = raw_max

    @staticmethod
    def _default_transition(state: DynamicState, cycle: int) -> DynamicState:
        """
        Default Transition: Linear Addition (*1 Medium coefficient, +0 Viscosity term).

        Changes value by +0.1 as an operation equivalent to `compute`.
        In real environments, swap `transition_fn` to use.
        """
        cost = 0.1   # Base cost

        # ── [EXT: viscosity] ─────────────────────────
        # Viscosity term: Suppress change in rate.
        # Current: * 1 (No suppression).
        # Implementation: cost *= state.viscosity_factor
        cost *= state.viscosity_factor   # [EXT: viscosity] *1

        # ── [EXT: pressure] ──────────────────────────
        # Pressure term: Additional cost.
        # Current: + 0.0
        # Implementation: cost += state.pressure * pressure_coefficient
        cost += state.pressure * 0.0     # [EXT: pressure] +0.0

        new_rate  = cost
        new_value = min(1.0, state.value + cost)
        state.rate  = new_rate
        state.value = new_value
        state.record(new_value)          # Record instantaneous value (do not average)
        return state

    def process(self, token: Token) -> Token:
        if token.meta.get("infeasible"):
            return self._record(token)
        token.state = self.transition_fn(token.state, token.meta["cycle"])
        # Energy Ledger: Record input amount
        token.ledger.E_in += token.state.rate
        return self._record(token)


class DisturbanceNode(Node):
    """
    Disturbance Injection Node.
    Specified by normalized value (magnitude ∈ [0, 1]).
    """

    def __init__(
        self,
        name: str,
        trigger_cycles: List[int],
        magnitude: float = 0.5,
    ):
        super().__init__(name)
        self.trigger_cycles = trigger_cycles
        self.magnitude = magnitude

    def process(self, token: Token) -> Token:
        if token.meta["cycle"] in self.trigger_cycles:
            self._logger.warning(
                f"Disturbance Injection [cycle={token.meta['cycle']}]: +{self.magnitude}"
            )
            prev = token.state.value
            token.state.value = min(1.0, token.state.value + self.magnitude)
            token.state.rate   = token.state.value - prev
            token.ledger.E_in += self.magnitude   # Account in Energy Ledger
            token.state.record(token.state.value)
        return self._record(token)


