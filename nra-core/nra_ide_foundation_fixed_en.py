# Law (Constraint / Dynamics Rule)
# ─────────────────────────────────────────────

class Law(ABC):
    """
    Abstract base class for dynamics rules acting on DynamicState.

    check()  : Whether constraints are satisfied.
    tension(): Restoring force (tension) proportional to distance from constraints.
    correct(): Correct the state using tension. Errors go to buffer.
    """

    @property
    def name(self) -> str:
        return self.__class__.__name__

    @abstractmethod
    def check(self, token: Token) -> bool: ...

    @abstractmethod
    def tension(self, token: Token) -> float:
        """
        Calculation of restoring force.
        Distance (excess amount) generates force — The principle that
        "deduction" does not derive force *from* distance, but implies
        "treating distance itself *as* force".
        Transformation via a proportional coefficient k is permissible.
        """
        ...

    @abstractmethod
    def correct(self, token: Token) -> Optional[Token]:
        """
        Correct using tension. Excess energy is escaped to buffer (not erased).
        Impossible correction → Returns None (Infeasibility).
        """
        ...


class BoundLaw(Law):
    """
    General Upper Bound Constraint.
    Guarantees that DynamicState.value does not exceed threshold.

    Tension: T = k * max(0, value - threshold)
    Correction: Pull value back to threshold - margin, move excess to buffer.
    """

    def __init__(
        self,
        threshold: float = 0.8,    # Upper limit (Normalized)
        k        : float = 1.0,    # Tension coefficient
        margin   : float = 0.05,   # Clip margin (Safe zone for next cycle)
    ):
        self.threshold = threshold
        self.k         = k
        self.margin    = margin

        # ── [EXT: viscosity_coupling] ─────────────────
        # Coupling viscosity to tension calculation (Add resistance as rate increases).
        # Current: +0.0
        # Implementation: T += viscosity * abs(token.state.rate)
        self._viscosity_coupling: float = 0.0  # [EXT: viscosity_coupling] +0.0

        # ── [EXT: brittle_threshold] ──────────────────
        # Brittle fracture point (Tension releases suddenly if this value is exceeded).
        # Current: * 1 (Remains standard linear tension).
        # Implementation: if value > brittle_threshold: T *= brittle_amplifier
        self._brittle_factor: float = 1.0      # [EXT: brittle_threshold] *1

    def check(self, token: Token) -> bool:
        return token.state.value <= self.threshold

    def tension(self, token: Token) -> float:
        excess = max(0.0, token.state.value - self.threshold)
        T = self.k * excess
        T += self._viscosity_coupling          # [EXT: viscosity_coupling]
        T *= self._brittle_factor              # [EXT: brittle_threshold]
        return T

    def correct(self, token: Token) -> Optional[Token]:
        T = self.tension(token)
        if T <= 0:
            return token

        excess = token.state.value - self.threshold
        target = self.threshold - self.margin

        # Escape excess energy to buffer (do not erase)
        token.state.buffer += excess
        token.state.value   = max(0.0, target)
        token.state.tension = T

        # Record in Energy Ledger (Aligned with JP version logic)
        # FIX: E_stored is cumulative difference (Corrected from overwriting normalized value -> causing errors)
        token.ledger.E_dissipated += excess
        token.ledger.E_stored     += max(0.0, target) - (token.state.value - excess)
        token.ledger.E_stored      = max(0.0, token.ledger.E_stored)  # Lower bound protection

        return token


class RateLimitLaw(Law):
    """
    Rate of Change Constraint (Foundation of Viscous Medium Model).
    Guarantees that rate does not exceed max_rate.

    Makes sudden spikes physically impossible — For Human Body / Soil Moisture systems.
    Disable (max_rate=inf) for Minerals / Pest systems.
    """

    def __init__(self, max_rate: float = 0.2):
        self.max_rate = max_rate

        # ── [EXT: rate_asymmetry] ─────────────────────
        # Set max_rate asymmetrically for increasing and decreasing directions.
        # Current: * 1 (Symmetric).
        # Implementation: Set max_rate_up / max_rate_down independently.
        self._rate_asymmetry: float = 1.0  # [EXT: rate_asymmetry] *1

    def check(self, token: Token) -> bool:
        return abs(token.state.rate) <= self.max_rate * self._rate_asymmetry

    def tension(self, token: Token) -> float:
        excess_rate = abs(token.state.rate) - self.max_rate
        return max(0.0, excess_rate)

    def correct(self, token: Token) -> Optional[Token]:
        if self.check(token):
            return token
        sign = 1.0 if token.state.rate >= 0 else -1.0
        # Accumulate exceeded rate into buffer
        token.state.buffer += abs(token.state.rate) - self.max_rate
        token.state.rate    = sign * self.max_rate
        return token


