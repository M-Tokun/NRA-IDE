@dataclass
class EnergyLedger:
    """
    Recorder for the Law of Conservation of Energy.
    Validates E_in = E_stored + E_dissipated (Conservation Law) every cycle.

    Errors are escaped to the buffer (not erased).
    """
    E_in       : float = 0.0   # Input Energy (Disturbance / Action Cost)
    E_stored   : float = 0.0   # Energy stored in the system
    E_dissipated: float = 0.0  # Dissipated Energy (Released via buffer)

    # ── [EXT: thermal_dissipation] ───────────────────
    # Thermal dissipation (Loss during high-speed fluctuations. Current: +0.0)
    E_thermal  : float = 0.0   # [EXT: thermal_dissipation] +0.0

    def balance(self) -> float:
        """Error in conservation law = E_in - (E_stored + E_dissipated)"""
        return self.E_in - (self.E_stored + self.E_dissipated + self.E_thermal)

    def is_conserved(self, tol: float = 1e-6) -> bool:
        return abs(self.balance()) < tol


