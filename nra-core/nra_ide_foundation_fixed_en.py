@dataclass
class DynamicState:
    """
    Medium-independent normalized state quantity. value ∈ [0.0, 1.0].

    All dynamic calculations pass through this container.
    Differences in media are expressed by Laws (transition functions), keeping the container shape unchanged.

    Field Descriptions:
      value   : Current state value (0=Complete Stability, 1=Critical Limit).
      rate    : Rate of change dv/dt (Velocity).
      buffer  : Energy waiting for dissipation (Escape for errors. Do not erase).
      tension : Restoring force generated by distance from constraints (Tension).
      history : History of instantaneous values (Record of protrusions/spikes. Do not average).
    """
    value  : float = 0.0
    rate   : float = 0.0
    buffer : float = 0.0
    tension: float = 0.0
    history: List[float] = field(default_factory=list)

    # ── [EXT: pressure] ──────────────────────────────
    # Pressure term (Human body / Fluid systems)
    # Current: + 0.0 because it is unused.
    # Implementation: Add `pressure: float = 0.0`, and in TensionLaw.compute():
    #   tension += pressure_coefficient * self.pressure
    pressure: float = 0.0   # [EXT: pressure] +0.0 (Unused)

    # ── [EXT: viscosity] ─────────────────────────────
    # Viscosity coefficient (Suppresses rate of change. Makes sudden spikes physically impossible).
    # Current: * 1 (Multiplication, so effectively disabled).
    # Implementation: rate_limited = rate * viscosity_factor (0 < v_factor <= 1)
    viscosity_factor: float = 1.0   # [EXT: viscosity] *1 (Disabled)

    # ── [EXT: plasticity] ────────────────────────────
    # Plasticity deformation coefficient (The baseline shifts after exceedance. History dependent).
    # Current: * 1 (No baseline change).
    # Implementation: threshold_shift += plasticity * max(0, value - threshold)
    plasticity_factor: float = 1.0  # [EXT: plasticity] *1 (Disabled)

    def record(self, v: float) -> None:
        """Record instantaneous value as is (do not average)."""
        self.history.append(v)

    def peak(self) -> float:
        """Protrusion value (Maximum instantaneous value)."""
        return max(self.history) if self.history else 0.0

    def normalize(self, raw: float, raw_max: float) -> float:
        """Normalize dimensional physical quantity to [0, 1]."""
        return min(1.0, max(0.0, raw / raw_max)) if raw_max > 0 else 0.0

    def denormalize(self, norm: float, raw_max: float) -> float:
        """Inverse transform [0, 1] to dimensional physical quantity."""
        return norm * raw_max


