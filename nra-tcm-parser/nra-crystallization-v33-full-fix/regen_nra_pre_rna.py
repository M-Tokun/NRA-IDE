from __future__ import annotations

from dataclasses import dataclass
from enum import Enum
import re


# ============================================================
# PolicyAction: 門の判定結果（3値のみ。中間状態は存在しない）
# ============================================================
class PolicyAction(str, Enum):
    """
    入力に対する門の判定結果。

    PASS    : 入力は正常。そのままLLMへ渡す。
    CONVERT : 注入試みを検出したが除去可能。
              除去後のテキストをLLMへ渡す。
              「悪意の部分を捨てて、本来の質問だけを通す」設計。
    BLOCK   : 通過を許可しない。パイプライン全体をFAIL_CLOSEDにする。
              空テキスト・秘密情報要求・除去不能な注入が該当。

    【設計思想】
      3値は「超えたか / ギリギリか / 超えていないか」ではない。
      「通す / 変換して通す / 通さない」という構造的な判定。
      スコアや確率による判定は存在しない。
    """
    PASS    = "PASS"
    CONVERT = "CONVERT"
    BLOCK   = "BLOCK"


# ============================================================
# PreRNAResult: 門の判定を運ぶ不変オブジェクト
# ============================================================
@dataclass(frozen=True)
class PreRNAResult:
    """
    PreRNAGateの判定結果を格納する不変データクラス。

    frozen=True の意味:
      一度生成された判定結果は変更できない。
      「判定した後から判定を書き換える」= 逆流（Π⁻¹）= 禁止。
      Causal Diodeの実装。

    フィールド:
      action : PolicyAction（PASS / CONVERT / BLOCK）
      text   : 後段へ渡すテキスト（BLOCKの場合は空文字）
      reason : なぜその判定になったかの記録（append-onlyログの材料）
    """
    action: PolicyAction
    text:   str
    reason: str = ""


# ============================================================
# PreRNAGate: 入力の純化を実行するクラス
# ============================================================
class PreRNAGate:
    """
    入力テキストを検査し、LLMへ渡す前に純化する「前蓋」。

    【処理の優先順位】
      1. 空テキスト → BLOCK（エネルギーなし → Stick状態も始まらない）
      2. 秘密情報の要求 → BLOCK（Gate Axiom: 生命・尊厳の聖域に近い概念）
      3. プロンプト注入 → CONVERT（注入を除去し、本来の入力だけを通す）
      4. 正常入力 → PASS

    【なぜ正規表現か】
      意味的な解釈（LLMによる判定）を使わない。
      構造的なパターンマッチングのみで判定する。
      「意味を理解して判断する」= 確率的 = FAIL_CLOSEDになれない。
      「パターンが一致するかしないか」= 決定論的 = FAIL_CLOSEDが確実に機能する。
    """

    def __init__(self) -> None:
        # ---------------------------------------------------
        # 注入検出パターン: 「ルールを無視せよ」系の命令を捕捉
        # ---------------------------------------------------
        # 対象: "ignore the instructions", "disregard these rules" 等
        # これらは「因果の上書き（Π⁻¹）」を要求する典型的な構文。
        # re.UNICODE: 日本語等の多言語入力にも対応
        self._inj = re.compile(
            r"(ignore|disregard).*(instructions|rules)", re.I | re.UNICODE
        )

        # ---------------------------------------------------
        # 秘密情報検出パターン: APIキー・パスワード等の要求を捕捉
        # ---------------------------------------------------
        # 対象: api_key, password, token, 秘密（日本語）, 鍵（日本語）
        # Gate Axiom 2（生命の聖域）の拡張として:
        #   秘密情報の漏洩は「人間の安全」に直結するため、
        #   確率的判定ではなく構造的遮断を適用する。
        # FIX: 前バージョンで文字化けしていた日本語を正しいUTF-8で記述
        self._secret = re.compile(
            r"(api[_\s]?key|password|token|秘密|鍵)", re.I | re.UNICODE
        )

    def run(self, user_text: str) -> PreRNAResult:
        """
        入力テキストを検査し、PreRNAResultを返す。

        【律環公理との対応】
          この関数が「Step 1: Input」の検査を担う。
          エネルギー（入力）が正当であることを確認してから、
          後段のStick（LongRunGuard）へ渡す。

        【重要: FAILは失敗ではない】
          BLOCKを返すことは「システムの失敗」ではない。
          「エネルギーが閾値に達していない = まだ動くべき時ではない」
          という正直な状態報告である。
          これがFAIL_CLOSEDの本質。
        """
        t = (user_text or "").strip()

        # ---------------------------------------------------
        # 判定1: 空テキスト → BLOCK
        # ---------------------------------------------------
        # エネルギーが存在しない（入力が空）なら、
        # 律環公理のStep 1（Input）が成立しない。
        # パイプライン全体をFAIL_CLOSEDにする。
        if not t:
            return PreRNAResult(PolicyAction.BLOCK, "", "empty")

        # ---------------------------------------------------
        # 判定2: 秘密情報の要求 → BLOCK
        # ---------------------------------------------------
        # Gate Axiom 2の適用:
        # 人間の安全・尊厳に関わる情報へのアクセスは
        # AIが判断する領域ではない。
        # 確率や文脈に関係なく、構造的に遮断する。
        if self._secret.search(t):
            return PreRNAResult(PolicyAction.BLOCK, "", "secret_exfil")

        # ---------------------------------------------------
        # 判定3: プロンプト注入の試み → CONVERT
        # ---------------------------------------------------
        # 「ルールを無視せよ」という命令を検出した場合:
        # 完全BLOCKではなく、注入部分を除去して本来の入力を通す。
        # 設計思想: 「悪意のある上書き命令」と「本来の質問」を分離する。
        # 注入を除去した後のテキストに正当な内容があれば、
        # それはパイプラインで処理されるべき入力である。
        if self._inj.search(t):
            cleaned = re.sub(self._inj, "", t).strip()
            return PreRNAResult(PolicyAction.CONVERT, cleaned, "prompt_injection")

        # ---------------------------------------------------
        # 判定4: 正常入力 → PASS
        # ---------------------------------------------------
        # 上記3つの検査を全て通過した入力のみがここに到達する。
        # Gear機構: 全リンクが存在する場合のみ動力を伝達する。
        return PreRNAResult(PolicyAction.PASS, t, "")
