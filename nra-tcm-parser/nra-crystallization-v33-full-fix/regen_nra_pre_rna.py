#
# 【PreRNAGateとは何か】
#   LLM（大規模言語モデル）への入力が到達する「最初の門」。
#   この門を通過しなければ、パイプライン全体が起動しない。
#
#   サンドイッチアーキテクチャにおける「前蓋（Pre-RNA）」として機能する。
#   前蓋と後蓋（Post-RNA = CrystallizationEngine）でLLMを挟むことで、
#   LLMが生成する確率的な出力を「因果構造の内側」に閉じ込める。
#
# 【なぜ入力を検査するか】
#   LLMは「prompt injection（指示の上書き）」に脆弱である。
#   悪意ある入力が「ルールを無視せよ」と命じた場合、
#   数学基盤のAIはその命令に従ってしまう可能性がある。
#
#   NRA-IDEは構造で防ぐ:
#     - 危険な入力 → BLOCK（FAIL_CLOSED）
#     - 注入試みあり → CONVERT（注入部を除去してから通過）
#     - 正常な入力 → PASS
#
# 【Causal Diodeとの関係】
#   逆流（Π⁻¹）の典型例:
#     「前の出力に合わせて、入力の解釈を変える」= 逆推論
#   この門は入力の時点でその芽を摘む。
#   入力は入力として純粋に扱われる。結果から入力を変えることはしない。
